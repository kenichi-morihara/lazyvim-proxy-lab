-- With installed plugins: XDG_CONFIG_HOME="$PWD/editor" nvim --headless -l tests/diffview.lua
local temp = vim.fn.tempname()
vim.fn.mkdir(temp, "p")
local function check(ok, message)
  assert(ok, message)
  print("PASS " .. message)
end
local function main()
  vim.go.loadplugins = true -- -l disables plugin loading by default.
  vim.opt.rtp:prepend(vim.fn.stdpath("config"))
  dofile(vim.fn.stdpath("config") .. "/init.lua")
  vim.api.nvim_exec_autocmds("User", { pattern = "VeryLazy" })
  vim.wait(100, function() return false end)
  local function git(...)
    local result = vim.system({ "git", "-C", temp, ... }, { text = true }):wait()
    assert(result.code == 0, result.stderr)
  end
  git("init", "-q")
  git("config", "user.name", "Test Fixture")
  git("config", "user.email", "fixture@example.invalid")
  vim.fn.writefile({ "before" }, temp .. "/sample.txt")
  git("add", ".")
  git("commit", "-qm", "fixture")
  vim.fn.writefile({ "after" }, temp .. "/sample.txt")
  vim.cmd.cd(temp)
  vim.cmd.edit(temp .. "/sample.txt")
  local original_tab = vim.api.nvim_get_current_tabpage()
  local original_buf = vim.api.nvim_get_current_buf()
  local function keys(value)
    vim.api.nvim_feedkeys(vim.api.nvim_replace_termcodes(value, true, false, true), "xt", false)
  end
  keys(" gd")
  vim.wait(100, function() return package.loaded["diffview.lib"] ~= nil end)
  local lib = require("diffview.lib")
  check(vim.wait(5000, function()
    local view = lib.get_current_view()
    return view and view.files:len() == 1 and view.cur_layout and not view.nulled
  end), "Space g d opens a real worktree diff")
  vim.wait(300, function() return false end) -- Let asynchronous layout/scroll setup finish.
  check(vim.api.nvim_get_current_tabpage() ~= original_tab, "diff opens in its own tab")
  local current_window = vim.api.nvim_get_current_win()
  keys(" wl")
  check(vim.api.nvim_get_current_win() ~= current_window, "Space w l navigates diff windows")
  vim.cmd.EditorClose()
  check(lib.get_current_view() == nil and vim.api.nvim_get_current_tabpage() == original_tab,
    "Ctrl+W command closes the entire view and returns to editing")
  check(vim.api.nvim_buf_is_valid(original_buf), "original editing buffer survives")
  keys(" gH")
  check(vim.wait(5000, function()
    local history = lib.get_current_view()
    return history and history.panel and history.panel.entries and #history.panel.entries > 0
  end), "Space g H loads actual file history")
  vim.wait(300, function() return false end)
  vim.cmd.DiffviewFocusFiles()
  keys("q")
  check(lib.get_current_view() == nil, "q closes the history view")
  vim.cmd.DiffviewOpen("HEAD")
  check(vim.wait(5000, function()
    local diff = lib.get_current_view()
    return diff and diff.files:len() == 1 and not diff.nulled
  end), "explicit revision comparison loads")
  vim.wait(300, function() return false end)
  vim.cmd.DiffviewFocusFiles()
  keys("<C-w>")
  check(lib.get_current_view() == nil, "Ctrl+W key closes the diff file panel")
  check(vim.v.errmsg == "", "no runtime errors during diff and history operations")
end
local ok, err = xpcall(main, debug.traceback)
vim.fn.delete(temp, "rf")
if not ok then io.stderr:write(err .. "\n"); vim.cmd("cquit 1") else vim.cmd("qa!") end
